/** Indexa por `MM-DD` para busca rápida. */
export const HOLY_DAYS_BY_KEY: Record<string, HolyDay[]> = HOLY_DAYS.reduce(
  (acc, day) => {
    const key = `${String(day.month).padStart(2, '0')}-${String(day.day).padStart(2, '0')}`;
    (acc[key] ??= []).push(day);
    return acc;
  },
  {} as Record<string, HolyDay[]>,
);

export function getHolyDays(month: number, day: number): HolyDay[] {
  const key = `${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
  return HOLY_DAYS_BY_KEY[key] ?? [];
}

